function ensure_completed_session(array $t, int $application_id, int $student_id, int $company_id): bool
{
    $dates = dataset_dates($t, time());
    $unfinished = ((int) $t['end']) > 0;
    $actual_end = $unfinished
        ? date('Y-m-d H:i:s', time() - 5 * 86400)
        : date('Y-m-d H:i:s', $dates['end']);

    $existing = db_fetch_one(
        "SELECT id, status FROM training_sessions WHERE application_id = ? LIMIT 1",
        [$application_id]
    );
    if ($existing) {
        return strtolower((string) $existing['status']) === 'completed';
    }
    db_execute(
        "INSERT INTO training_sessions
            (application_id, training_id, student_id, company_id, status, started_at,
             trial_started_at, trial_ends_at, student_continuation_confirmed_at,
             actual_ended_at, employment_opportunity, created_at, updated_at)
         VALUES (?, ?, ?, ?, 'completed', ?, ?, ?, ?, ?, ?, NOW(), NOW())",
        [
            $application_id, (int) $t['id'], $student_id, $company_id,
            date('Y-m-d H:i:s', $dates['start']),
            date('Y-m-d H:i:s', $dates['start']),
            date('Y-m-d H:i:s', $dates['start'] + (int) $t['trial'] * 86400),
            date('Y-m-d H:i:s', $dates['start'] + (int) $t['trial'] * 2 * 86400),
            $actual_end, (int) $t['lead'],
        ]
    );
    return true;
}

