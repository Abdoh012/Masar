function dataset_dates(array $t, int $now): array
{
    $days = (int) $t['end'];
    $end  = $now + $days * 86400;
    $start = $end - (int) $t['weeks'] * 7 * 86400;
    return [
        'published' => $start - 20 * 86400,
        'deadline'  => $start - 3 * 86400,
        'start'     => $start,
        'end'       => $end,
    ];
}

