$state_report = [];
$buckets = [];
foreach ($TRAININGS as $t) {
    $tid = (int) $t['id'];
    if (in_array($tid, $PENDING_IDS, true)) {
        $bucket = 'pending';
    } elseif (in_array($tid, $ISSUED_IDS, true)) {
        $bucket = 'issued';
    } elseif (in_array($tid, $REVOKED_IDS, true)) {
        $bucket = 'revoked';
    } elseif (in_array($tid, $ELIGIBLE_IDS, true)) {
        $bucket = 'eligible';
    } elseif ($tid === $UNFINISHED) {
        $bucket = 'unfinished';
    } else {
        $bucket = 'unknown';
    }
    $buckets[$tid] = $bucket;

    if ($bucket === 'eligible' || $bucket === 'unfinished') {
        $existing = dataset_cert($STUDENT_ID, $tid);
        if ($existing) {
            // Any certificate on an eligible/unfinished dataset training is a
            // test-owned leftover from a crashed run - converge by removing it.
            db_execute("DELETE FROM certificate_appeals WHERE certificate_id = ?", [(int) $existing['id']]);
            db_execute("DELETE FROM notifications WHERE entity_type = 'certificate' AND entity_id = ?", [(int) $existing['id']]);
            db_execute("DELETE FROM certificates WHERE id = ?", [(int) $existing['id']]);
            seed_check("$tid cleaned of a leftover certificate (crashed-run residue)", true);
        } else {
            seed_check("$tid stays eligible-free (no cert)", true);
        }
        continue;
    }

    $reason = (string) ($t['reason'] ?? '');
    $outcome = converge_cert($reset, $student_user, $company_user, $STUDENT_ID, $tid, $bucket, $reason);
    seed_check("certificate $tid -> {$outcome}", str_starts_with($outcome, $bucket));
    $state_report[$tid] = $outcome;
}

echo "\n== Assigning grade data (issued + revoked only, fill-if-null) ==\n";

$grade_tids = array_keys($GRADES);
$grade_certs = db_fetch_all(
    "SELECT c.id, c.training_id, c.grade, c.grade_label
     FROM certificates c
     WHERE c.student_id = ?
       AND c.training_id IN (" . implode(',', array_fill(0, count($grade_tids), '?')) . ")
     ORDER BY c.training_id",
    array_merge([$STUDENT_ID], $grade_tids)
);
$grades_assigned = 0;
foreach ($grade_certs as $cert) {
    $pair = $GRADES[(int) $cert['training_id']] ?? null;
    if ($pair === null) { continue; }
    $has_grade = $cert['grade'] !== null && (string) $cert['grade'] !== '';
    if (!$has_grade) {
        db_execute(
            "UPDATE certificates SET grade = ?, grade_label = ?, updated_at = NOW() WHERE id = ?",
            [$pair['grade'], $pair['grade_label'], (int) $cert['id']]
        );
        $grades_assigned++;
    }
}
$grade_certs_after = db_fetch_all(
    "SELECT c.training_id, c.grade, c.grade_label
     FROM certificates c
     WHERE c.student_id = ?
       AND c.training_id IN (" . implode(',', array_fill(0, count($grade_tids), '?')) . ")
     ORDER BY c.training_id",
    array_merge([$STUDENT_ID], $grade_tids)
);
$grades_ok = true;
foreach ($grade_certs_after as $cert) {
    $tid = (int) $cert['training_id'];
    $pair = $GRADES[$tid] ?? null;
    $match = $pair !== null
        && (string) $cert['grade'] === (string) $pair['grade']
        && (string) $cert['grade_label'] === (string) $pair['grade_label'];
    if (!$match) {
        $grades_ok = false;
        echo "FAIL - certificate for training {$tid}: expected " . ($pair['grade'] ?? '?') . " / " . ($pair['grade_label'] ?? '?') . ", got " . var_export($cert['grade'], true) . " / " . var_export($cert['grade_label'], true) . "\n";
    }
}
seed_check('all issued/revoked dataset certificates carry the expected grade data', $grades_ok);
seed_check("$grades_assigned new grade(s) assigned (0 on idempotent re-run)", $grades_assigned >= 0);

