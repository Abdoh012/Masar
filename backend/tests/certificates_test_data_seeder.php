seed_check('every issued/revoked cert carries a generated number + issued_at; revoked keep reasons', $all_finished_ok);

/*
| Grade rules that must hold after the seeder:
|   issued   -> grade + grade_label are populated
|   revoked  -> preserves the historical grade (issued before revocation)
|   pending  -> grade + grade_label stay NULL
|   eligible / unfinished -> no certificate row, hence no grade at all
| Distribution is not uniform (at least 3 distinct grades on issued certs).
*/
$grade_rows = db_fetch_all(
    "SELECT c.status, c.grade, c.grade_label
     FROM certificates c
     WHERE c.student_id = ?
     ORDER BY c.training_id",
    [$STUDENT_ID]
);
$issued_without_grade = 0;
$revoked_without_grade = 0;
$pending_with_grade = 0;
$issued_grades = [];
foreach ($grade_rows as $gr) {
    $st = strtolower((string) $gr['status']);
    $has = $gr['grade'] !== null && (string) $gr['grade'] !== '' && $gr['grade_label'] !== null && (string) $gr['grade_label'] !== '';
    if ($st === 'issued') {
        if (!$has) { $issued_without_grade++; }
        $issued_grades[] = (string) $gr['grade'];
    }
    if ($st === 'revoked' && !$has) { $revoked_without_grade++; }
    if ($st === 'pending' && $has) { $pending_with_grade++; }
}
sort($issued_grades);
seed_check('every issued certificate has grade + grade_label', $issued_without_grade === 0);
seed_check('every revoked certificate preserves its historical grade', $revoked_without_grade === 0);
seed_check('no pending certificate carries a grade (all NULL)', $pending_with_grade === 0);
seed_check('issued certificates use a non-uniform grade distribution', count(array_unique($issued_grades)) >= 3);

$eligible_now = certificate_repository_eligible(['student_id' => $STUDENT_ID]);
