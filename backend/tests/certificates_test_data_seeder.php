function converge_cert(bool $reset, array $student_user, array $company_user, int $student_id, int $training_id, string $target, string $reason = ''): string
{
    $cert = dataset_cert($student_id, $training_id);
    $status = $cert ? strtolower((string) $cert['status']) : '';
    $cid    = $cert ? (int) $cert['id'] : 0;

    if ($reset && $cert) {
        db_execute("DELETE FROM certificate_appeals WHERE certificate_id = ?", [$cid]);
        db_execute("DELETE FROM notifications WHERE entity_type = 'certificate' AND entity_id = ?", [$cid]);
        db_execute("DELETE FROM certificates WHERE id = ?", [$cid]);
        $cert = [];
        $status = '';
        $cid = 0;
    }

    if ($status === $target) {
        return $target . ' (already, id ' . $cid . ')';
    }

    if ($target === 'pending') {
        if ($status === '') {
            $req = certificate_service_request($student_user, ['training_id' => $training_id]);
            if (($req['success'] ?? false) !== true) {
                return 'request-failed';
            }
            return 'pending';
        }
        return 'conflict-with-' . $status;
    }

    if ($target === 'issued') {
        if ($status === '') {
            $req = certificate_service_request($student_user, ['training_id' => $training_id]);
            if (($req['success'] ?? false) !== true) {
                return 'request-failed';
            }
            $cert = dataset_cert($student_id, $training_id);
            $status = strtolower((string) ($cert['status'] ?? ''));
            $cid = (int) ($cert['id'] ?? 0);
        }
        if ($status === 'issued') {
            return 'issued (id ' . $cid . ')';
        }
        if ($status === 'pending') {
            $conf = certificate_service_confirm($company_user, (int) $cid);
            if (($conf['success'] ?? false) !== true) {
                return 'confirm-failed';
            }
            return 'issued';
        }
        return 'conflict-with-' . $status;
    }

    if ($target === 'revoked') {
        if ($status === '') {
            $req = certificate_service_request($student_user, ['training_id' => $training_id]);
            if (($req['success'] ?? false) !== true) {
                return 'request-failed';
            }
            $cert = dataset_cert($student_id, $training_id);
            $status = strtolower((string) ($cert['status'] ?? ''));
            $cid = (int) ($cert['id'] ?? 0);
        }
        if ($status === 'revoked') {
            return 'revoked (id ' . $cid . ')';
        }
        if (in_array($status, ['pending', 'issued'], true)) {
            $conf = certificate_service_confirm($company_user, (int) $cid);
            if (($conf['success'] ?? false) !== true) {
                return 'confirm-failed';
            }
            $rev = certificate_service_revoke($company_user, (int) $cid, ['reason' => $reason]);
            if (($rev['success'] ?? false) !== true) {
                return 'revoke-failed';
            }
            return 'revoked';
        }
        return 'conflict-with-' . $status;
    }

    return 'unknown-target';
}

