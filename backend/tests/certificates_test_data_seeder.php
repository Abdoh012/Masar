$by_status = ['pending' => 0, 'issued' => 0, 'revoked' => 0];
$all_finished_ok = true;
foreach ($all_certs as $c) {
    $st = strtolower((string) $c['status']);
    if (isset($by_status[$st])) {
        $by_status[$st]++;
    }
    if ($st !== 'pending') {
        if (($c['certificate_code'] ?? '') === '' || ($c['approved_at'] ?? '') === '') {
            $all_finished_ok = false;
        }
    }
    if ($st === 'revoked') {
        if (($c['revoked_at'] ?? '') === '' || trim((string) ($c['revocation_reason'] ?? '')) === '') {
            $all_finished_ok = false;
        }
    }
}
